-- Phase 5.7: isolated lecturer-demo credentials. Do not alter student auth or warehouse facts.
CREATE TABLE IF NOT EXISTS auth.demo_lecturer_accounts (
 lecturer_account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(80) NOT NULL UNIQUE,
 display_name varchar(200) NOT NULL,
 instructor_key integer NOT NULL REFERENCES warehouse.dim_instructor(instructor_key),
 password_hash text NOT NULL,
 is_active boolean NOT NULL DEFAULT true,
 failed_attempts integer NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
 locked_until timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS auth.demo_lecturer_sessions (
 session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lecturer_account_id bigint NOT NULL REFERENCES auth.demo_lecturer_accounts(lecturer_account_id) ON DELETE CASCADE,
 token_hash char(64) NOT NULL UNIQUE,
 expires_at timestamptz NOT NULL,
 revoked_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_demo_lecturer_sessions_account ON auth.demo_lecturer_sessions(lecturer_account_id);
CREATE INDEX IF NOT EXISTS idx_demo_lecturer_sessions_expiry ON auth.demo_lecturer_sessions(expires_at);
