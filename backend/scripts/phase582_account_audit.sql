-- Additive account lifecycle audit. No changes to Warehouse or password storage.
CREATE TABLE IF NOT EXISTS auth.demo_admin_account_audit (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_admin_account_id bigint NOT NULL REFERENCES auth.demo_admin_accounts(admin_account_id),
    target_role varchar(20) NOT NULL CHECK (target_role IN ('student','lecturer','admin')),
    target_username varchar(80) NOT NULL,
    previous_active boolean NOT NULL,
    new_active boolean NOT NULL,
    reason varchar(500) NOT NULL,
    sessions_revoked integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT demo_admin_audit_real_transition CHECK (previous_active <> new_active)
);
CREATE INDEX IF NOT EXISTS idx_admin_account_audit_created ON auth.demo_admin_account_audit(created_at DESC);
