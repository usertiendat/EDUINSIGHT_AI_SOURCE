-- Only new auth tables; safe to run repeatedly. No warehouse records are changed.
BEGIN;
CREATE SCHEMA IF NOT EXISTS auth;
CREATE TABLE IF NOT EXISTS auth.demo_accounts (
  account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(80) NOT NULL UNIQUE,
  display_name varchar(200) NOT NULL,
  role varchar(20) NOT NULL DEFAULT 'student' CHECK (role = 'student'),
  student_key integer NOT NULL REFERENCES warehouse.dim_student(student_key),
  password_hash text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  failed_attempts integer NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
  locked_until timestamptz,
  last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS auth.demo_sessions (
  session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES auth.demo_accounts(account_id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_demo_sessions_account ON auth.demo_sessions(account_id);
CREATE INDEX IF NOT EXISTS idx_demo_sessions_expiry ON auth.demo_sessions(expires_at);
COMMIT;
